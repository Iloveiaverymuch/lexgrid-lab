"""Generate the promptfoo quality suite from the golden set (single source of truth for labels).

uv run python scripts/build_promptfoo.py          # rewrite evals/promptfoo/quality.tests.yaml
uv run python scripts/build_promptfoo.py --check  # fail if the file is out of date (used by the tests)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from lexgrid.evals.runner import load_golden  # noqa: E402

GOLDEN = ROOT / "evals" / "golden" / "golden_v1.yaml"
OUT = ROOT / "evals" / "promptfoo" / "quality.tests.yaml"
HEADER = "# GENERATED by scripts/build_promptfoo.py from evals/golden/golden_v1.yaml. Do not edit by hand.\n"


def render() -> str:
    tests = []
    for q in load_golden(GOLDEN):
        base = {
            "description": f"{q.id} [{q.type}] {q.query}",
            "vars": {"query": q.query, "jurisdictions": ",".join(q.scope)},
        }
        if q.type == "no_answer":
            base["vars"]["endpoint"] = "ask"
            base["assert"] = [
                {
                    "type": "javascript",
                    "value": "output.status === 200 && output.body.abstained === true",
                    "metric": "abstains_when_out_of_corpus",
                }
            ]
        else:
            relevant = json.dumps(sorted(k for k, g in q.qrels.items() if g >= 1), ensure_ascii=False)
            best = json.dumps(sorted(k for k, g in q.qrels.items() if g == 2), ensure_ascii=False)
            asserts = [
                {
                    "type": "javascript",
                    "value": f"output.body.hits.slice(0, 5).some(h => {relevant}.includes(h.article_key))",
                    "metric": "hit@5",
                }
            ]
            if q.type == "exact_ref":
                asserts.append(
                    {
                        "type": "javascript",
                        "value": f"{best}.includes(output.body.hits[0].article_key)",
                        "metric": "exact_reference_at_rank_1",
                    }
                )
            base["assert"] = asserts
        tests.append(base)
    return HEADER + json.dumps(tests, indent=2, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/build_promptfoo.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
